def get_faq_answer(key: str) -> str | None:
    """
    Возвращает готовый HTML-ответ по ключу.

    Например:

    get_faq_answer("waiting")

    вернет текст про сроки доставки.
    """

    faq = FAQ_DATA.get(key)

    if not faq:
        return None

    return faq["answer"]